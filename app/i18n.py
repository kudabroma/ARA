def normalize_language(language: str) -> str:
    return language.lower() if language.lower() in LANGUAGES else "en"


def tr(language: str, key: str, **values: Any) -> str:
    lang = normalize_language(language)
    return _TEXTS[lang][key].format(**values)


def translate_source_text(language: str, text: str) -> str:
    key = _SOURCE_KEYS.get(text)
    return tr(language, key) if key else text


def localized_period(language: str, period: str) -> str:
    lang = normalize_language(language)
    match = re.fullmatch(r"([A-Z][a-z]{2}) (\d{1,2}) – ([A-Z][a-z]{2}) (\d{1,2}), (\d{4})", period)
    if not match or lang == "en":
        return period

    start_month, start_day, end_month, end_day, year = match.groups()
    start = datetime.strptime(f"{start_month} {start_day} {year}", "%b %d %Y")
    end = datetime.strptime(f"{end_month} {end_day} {year}", "%b %d %Y")
    months = _MONTHS[lang]
    if lang == "ru":
        return f"{start.day} {months[start.month - 1]} – {end.day} {months[end.month - 1]} {year} г."
    return f"{start.day} {months[start.month - 1]} – {end.day} {months[end.month - 1]} de {year}"
